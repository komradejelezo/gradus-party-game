import type { Card, Category, Resolution, Effect } from "../game-engine/types";
const basic: Effect = { success: 1, failure: -1 };
function card(
  category: Category,
  n: number,
  title: string,
  instruction: string,
  resolution: Resolution = "Суд компании",
  participation = "Один игрок",
  duration = 30,
  effect: Effect = basic,
  toast = false,
): Card {
  const transferInstructions: Record<string, string> = {
    "chaos-1":
      "Объясни слово «штопор», не используя «вино», «пробка» и «бутылка». Стол должен угадать за 30 секунд.",
    "chaos-5": "20 секунд рекламируй собственный локоть, не смеясь.",
    "chaos-12":
      "Произнеси тост в честь носка, будто вручаешь ему премию. Нужны номинация, заслуга и благодарность.",
  };
  return {
    ...(effect.target
      ? { transferInstruction: transferInstructions[`${category}-${n}`] }
      : {}),
    id: `${category}-${String(n).padStart(2, "0")}`,
    category,
    title,
    instruction,
    resolution,
    participation,
    duration,
    effect,
    ...(toast ? { toast: true } : {}),
  };
}
